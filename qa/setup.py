#!/usr/bin/env python3
"""
One-command, idempotent machine setup for the Adhoc QA agent (stdlib only).
The agent runs this automatically at the start of /qa-start, /qa-continue, /qa-charter and /qa-learn,
so a colleague who clones the repo never has to do manual setup.

  python3 qa/setup.py        -> prints "ok ..." lines, "FIX ..." lines (needs a human) and/or "RESTART ..."

What it does:
  1. Python deps (PyYAML, markdown): uses them if importable, else creates .venv and installs there.
  2. qa/.env.qa: if missing, builds it from the automation framework's .env, copying ONLY the
     secret names used by roles in qa.config.yaml. Removes any other keys (they would be masked
     on every page). Never prints values.
  3. Checks Node.js (for the browser server) and Google Chrome.
  4. Reports whether the shared app model (qa/knowledge/app-model.md) exists.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

QA = Path(__file__).resolve().parent
WS = QA.parent
CONFIG = QA / "qa.config.yaml"
ENV_QA = QA / ".env.qa"
ENV_EXAMPLE = QA / ".env.qa.example"
VENV = WS / ".venv"
VENV_PY = VENV / ("Scripts/python.exe" if os.name == "nt" else "bin/python")

fixes: list[str] = []
restart = False


def ok(msg: str) -> None:
    print(f"ok {msg}")


def fix(msg: str) -> None:
    fixes.append(msg)
    print(f"FIX {msg}")


def cfg_text() -> str:
    try:
        return CONFIG.read_text(encoding="utf-8")
    except OSError:
        return ""


def cfg_value(key: str) -> str | None:
    m = re.search(rf'^{re.escape(key)}\s*:\s*["\']?([^"\'#\n]+?)["\']?\s*(?:#.*)?$', cfg_text(), re.M)
    return m.group(1).strip() if m else None


def needed_secret_names() -> list[str]:
    # role secrets from non-commented lines only
    names = re.findall(r'^\s*(?:-\s*)?(?:username_secret|password_secret)\s*:\s*["\']?([A-Za-z_][A-Za-z0-9_]*)',
                       cfg_text(), re.M)
    return list(dict.fromkeys(names))


def parse_env(text: str) -> list[tuple[str, str, str]]:
    """Return (key, raw_line, kind) where kind is 'kv' or 'other' (comments/blank)."""
    out = []
    for line in text.splitlines():
        m = re.match(r"^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=", line)
        out.append((m.group(1), line, "kv") if m else ("", line, "other"))
    return out


def check_python() -> None:
    if sys.version_info < (3, 9):
        fix(f"Python 3.9+ needed (found {sys.version.split()[0]}). Install Python 3.")
        return
    try:
        import yaml  # noqa: F401
        import markdown  # noqa: F401
        ok("python deps present")
        return
    except ImportError:
        pass
    if VENV_PY.exists() and subprocess.run([str(VENV_PY), "-c", "import yaml, markdown"],
                                           capture_output=True).returncode == 0:
        ok("python deps present in .venv")
        return
    try:
        if not VENV_PY.exists():
            subprocess.run([sys.executable, "-m", "venv", str(VENV)], check=True,
                           stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        subprocess.run([str(VENV_PY), "-m", "pip", "install", "-q", "--disable-pip-version-check",
                        "-r", str(QA / "requirements.txt")], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
        subprocess.run([str(VENV_PY), "-c", "import yaml"], check=True)
        ok("python deps installed in .venv (ledger.py uses it automatically)")
    except (subprocess.CalledProcessError, OSError) as e:
        err = getattr(e, "stderr", b"") or b""
        fix("could not install PyYAML. Run: python3 -m venv .venv && .venv/bin/pip install -r qa/requirements.txt"
            + (f" (error: {err.decode(errors='ignore').strip().splitlines()[-1][:160]})" if err else ""))


def framework_dir() -> Path | None:
    fw = cfg_value("framework_path")
    if not fw or fw.startswith("/path/to"):
        return None
    p = Path(os.path.expanduser(fw))
    return (p if p.is_absolute() else (WS / p)).resolve()


def check_env_qa() -> None:
    global restart
    need = needed_secret_names()
    if not need:
        fix("no roles with username_secret/password_secret in qa/qa.config.yaml")
        return
    if not ENV_QA.exists():
        fw = framework_dir()
        src = (fw / ".env") if fw else None
        if src and src.is_file():
            vals = {k: line for k, line, kind in parse_env(src.read_text(encoding="utf-8", errors="ignore"))
                    if kind == "kv"}
            got = [k for k in need if k in vals]
            if got:
                body = ["# Generated by qa/setup.py from the automation framework's .env (only the keys the agent needs).",
                        "# Never commit this file."] + [vals[k] for k in got]
                ENV_QA.write_text("\n".join(body) + "\n", encoding="utf-8")
                try:
                    os.chmod(ENV_QA, 0o600)
                except OSError:
                    pass
                restart = True
                ok(f"created qa/.env.qa from framework .env with: {', '.join(got)}")
            missing = [k for k in need if k not in vals]
            if missing:
                fix(f"add to qa/.env.qa (NAME=value): {', '.join(missing)}")
                if not got:
                    shutil.copyfile(ENV_EXAMPLE, ENV_QA)
                    restart = True
            return
        if ENV_EXAMPLE.exists():
            shutil.copyfile(ENV_EXAMPLE, ENV_QA)
            restart = True
        fix(f"fill your test credentials in qa/.env.qa: {', '.join(need)} (or set framework_path so setup can copy them)")
        return

    entries = parse_env(ENV_QA.read_text(encoding="utf-8", errors="ignore"))
    keys = [k for k, _, kind in entries if kind == "kv"]
    extra = [k for k in keys if k not in need]
    if extra:
        kept = [line for k, line, kind in entries if kind == "other" or k in need]
        ENV_QA.write_text("\n".join(kept) + "\n", encoding="utf-8")
        restart = True
        ok(f"removed non-credential keys from qa/.env.qa (they get masked on every page): {', '.join(extra)}")
    missing = [k for k in need if k not in keys]
    if missing:
        fix(f"add to qa/.env.qa (NAME=value): {', '.join(missing)}")
    elif not extra:
        ok(f"qa/.env.qa has {', '.join(need)}")
    placeholder = re.compile(r"=\s*[\"']?(change-me|qa\.user@example\.com)?[\"']?\s*$")
    if any(kind == "kv" and k in need and placeholder.search(line) for k, line, kind in entries):
        fix("qa/.env.qa still has empty/example values - put the real test credentials")


def check_node_chrome() -> None:
    node = shutil.which("node")
    if not node or not shutil.which("npx"):
        fix("install Node.js 18+ (needed for the browser server): https://nodejs.org")
    else:
        try:
            v = subprocess.run([node, "-v"], capture_output=True, text=True, timeout=10).stdout.strip()
            major = int(v.lstrip("v").split(".")[0])
            (ok if major >= 18 else fix)(f"node {v}" if major >= 18 else f"Node.js 18+ needed (found {v})")
        except Exception:
            ok("node found")
    cands = []
    if sys.platform == "darwin":
        cands = [Path("/Applications/Google Chrome.app"), Path.home() / "Applications/Google Chrome.app"]
    elif os.name == "nt":
        for env in ("PROGRAMFILES", "PROGRAMFILES(X86)", "LOCALAPPDATA"):
            if os.environ.get(env):
                cands.append(Path(os.environ[env]) / "Google/Chrome/Application/chrome.exe")
    else:
        cands = [Path(p) for p in filter(None, [shutil.which("google-chrome"), shutil.which("google-chrome-stable")])]
    if any(c.exists() for c in cands):
        ok("Google Chrome found")
    else:
        fix("install Google Chrome (the agent drives a separate Chrome profile)")


def check_knowledge() -> None:
    am = QA / "knowledge" / "app-model.md"
    if am.exists():
        ok(f"app model present ({sum(1 for _ in am.open(encoding='utf-8'))} lines)")
    else:
        print("INFO no qa/knowledge/app-model.md yet - run /qa-learn once and commit it for the team")
    fw = framework_dir()
    if fw and not fw.is_dir():
        print(f"INFO framework_path not found on this machine ({fw}); only /qa-learn needs it")


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass
    check_python()
    check_env_qa()
    check_node_chrome()
    check_knowledge()
    if restart:
        print("RESTART playwright server: Agent Customizations > MCP Servers > playwright > ... > Restart Server "
              "(qa/.env.qa changed)")
    print("SETUP OK" if not fixes else f"SETUP NEEDS {len(fixes)} FIX(ES)")
    sys.exit(0 if not fixes else 1)


if __name__ == "__main__":
    main()
